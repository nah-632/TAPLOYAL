#!/usr/bin/env node
/**
 * tools/provision-app-role.mjs
 *
 * Gives the restricted runtime role (`taployal_app`) a password and writes the
 * resulting DATABASE_URL into .env.local (git-ignored).
 *
 * WHY the runtime must NOT use the admin role: `admin` has rolsuper + rolbypassrls,
 * so connecting as it silently disables every RLS policy (ADR-001 §17).
 *
 * SECRET HANDLING: the password is generated here, sent to PostgreSQL, and
 * written to .env.local. It is never printed, logged, or echoed — this script
 * deliberately prints only a redacted confirmation.
 *
 * Usage: node tools/provision-app-role.mjs [--host 1.2.3.4] [--port 5432]
 */
import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const API = "https://app.cranl.com/api/v1";
const DB = process.env.CRANL_TAPLOYAL_DB_ID ?? "864dd005-bcd2-4662-a2bf-1603beea1811";
const KEY = process.env.CRANL_ACCESS_KEY;

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};

/**
 * NOTE (security): the external host/port are deliberately NOT hard-coded.
 * This repository is public, and publishing the address of an
 * internet-reachable PostgreSQL port advertises it to scanners. Supply them
 * via --host/--port or the CRANL_DB_EXTERNAL_* environment variables.
 */
const HOST = arg("--host", process.env.CRANL_DB_EXTERNAL_HOST ?? "");
const PORT = arg("--port", process.env.CRANL_DB_EXTERNAL_PORT ?? "");
const DBNAME = arg("--dbname", "taployal_db");

if (!HOST || !PORT) {
  console.error(
    "usage: provision-app-role.mjs --host <h> --port <p> [--dbname taployal_db] [--sslmode disable]\n" +
      "(or set CRANL_DB_EXTERNAL_HOST / CRANL_DB_EXTERNAL_PORT)",
  );
  process.exit(2);
}
/**
 * SECURITY FINDING (2026-11-09): CranL's external PostgreSQL port does NOT
 * support TLS — connecting with sslmode=require fails with SSL_NOT_SUPPORTED.
 * Any external connection therefore crosses the public internet in cleartext.
 * This is acceptable ONLY for a throwaway dev database with synthetic rows.
 * Production must connect from inside CranL over the internal host.
 */
const SSLMODE = arg("--sslmode", "require");
if (SSLMODE === "disable") {
  console.warn("⚠  sslmode=disable: credentials and data will cross the public");
  console.warn("   internet in CLEARTEXT. Dev-only. Close external access afterwards.");
}

async function query(sql, write = true) {
  const post = async (payload) => {
    const res = await fetch(`${API}/databases/${DB}/query`, {
      method: "POST",
      headers: { Authorization: `Bearer ${KEY}`, "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
    return res.json().catch(() => null);
  };
  let json = await post({ query: sql, write });
  if (json?.error?.code === "confirmation_required") {
    json = await post({ query: sql, write, confirm: json.error.details?.confirm_token });
  }
  if (json?.error) throw new Error(`${json.error.code}: ${json.error.message}`);
  return json;
}

// 32 bytes of entropy, URL-safe so it needs no encoding in a connection URL.
const password = randomBytes(32).toString("base64url");

// The SQL is sent but never echoed: the API's confirmation summary would
// otherwise contain the plaintext password.
await query(`ALTER ROLE taployal_app WITH LOGIN PASSWORD '${password}'`);
console.log("✓ password set for role taployal_app (value never printed)");

const url = `postgres://taployal_app:${password}@${HOST}:${PORT}/${DBNAME}?sslmode=${SSLMODE}`;

// Verify the new credential actually authenticates before persisting it.
const { default: postgres } = await import("postgres");
let ok = false;
try {
  const sql = postgres(url, { max: 1, connect_timeout: 15, prepare: false });
  const rows = await sql`select current_user as usr, rolbypassrls as bypass, rolsuper as s
                         from pg_roles where rolname = current_user`;
  ok = rows[0]?.usr === "taployal_app" && rows[0]?.bypass === false && rows[0]?.s === false;
  console.log(`  connection test: user=${rows[0]?.usr} bypasrls=${rows[0]?.bypass} super=${rows[0]?.s}`);
  await sql.end({ timeout: 5 });
} catch (e) {
  console.error("  connection test FAILED:", e.message);
}

if (!ok) {
  console.error("✗ refusing to write DATABASE_URL — the credential did not verify");
  process.exit(1);
}

const envPath = new URL("../.env.local", import.meta.url).pathname;
let body = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
if (/^DATABASE_URL=/m.test(body)) {
  body = body.replace(/^DATABASE_URL=.*$/m, `DATABASE_URL=${url}`);
} else {
  body += `${body.endsWith("\n") || body === "" ? "" : "\n"}DATABASE_URL=${url}\n`;
}
body = `# Runtime database connection (restricted role, NOBYPASSRLS).\n# Generated by tools/provision-app-role.mjs — git-ignored.\n${body}`;
writeFileSync(envPath, body, { mode: 0o600 });

console.log("✓ wrote DATABASE_URL to .env.local (mode 600, git-ignored)");
